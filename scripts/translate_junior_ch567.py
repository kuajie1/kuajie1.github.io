def inject(src_path, nd_path, idx, tr_list):
    for p in (src_path, nd_path):
        d = json.load(open(p, encoding="utf-8"))
        ch = d["chapters"][idx]
        assert len(ch["sentences"]) == len(tr_list), f"{p} idx={idx} len mismatch {len(ch['sentences'])} vs {len(tr_list)}"
        for s, t in zip(ch["sentences"], tr_list):
            s["zh"] = t
        # 整章译文（去引号拼接）
        ch["zh"] = "".join(tr_list)
        json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print("written", os.path.basename(p), "ch", idx, "sentences", len(tr_list))

